export type PortfolioMessages = ReturnType<typeof usePortfolioMessages>;

/** Display name of a sector key (IB industry or one of the special buckets). */
export function sectorLabel(m: PortfolioMessages, key: string): string {
  return m.sectorNames[key] ?? key;
}

/**
 * A positions-table column's tooltip: where the value comes from ("IB · …") or, for a calculated
 * column, "Calculated by Tape:" and the formula; then its full name.
 */
export function columnTip(m: PortfolioMessages, id: ColumnId): string {
  const how = COLUMNS[id].kind === 'calc' ? `${m.calculatedBy} ${m.formulas[id] ?? ''}` : `IB · ${m.sources[id] ?? ''}`;
  return `${how}\n${m.columns[id][1]}`;
}
